// Independent transcription of Schirmer (1900), printed pp.98–115.
// All newly entered note data in this file are dedicated to CC0.
import {writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {normalizeScore} from '../public/score-model.mjs';
export function transcribeHanonFinal(){
const rows=[],sourceUrl='https://s9.imslp.org/files/imglnks/usimg/1/1b/IMSLP91547-PMLP03129-Hanon_Final.pdf';
const range=(a,b)=>Array.from({length:Math.abs(b-a)+1},(_,i)=>a+i*Math.sign(b-a));
const repeat=(x,n)=>Array.from({length:n},()=>x).flat();
function add(number,suffix,title,right,left,{pages,bpm=60,keySignature='C',duration=.25,final=false,description='',timeSignature=[4,4]}={}){
 const notes=[];for(const[hand,seq]of [['right',right],['left',left]]){let beat=0;for(const item of seq){const pitches=typeof item==='number'?[item]:Array.isArray(item)?item:item.pitches,dur=item.duration??duration;for(const pitch of pitches)notes.push({id:`h${number}-${suffix}-${hand[0]}-${notes.length}`,pitch,beat,duration:dur,hand});beat+=dur;}}
 let totalBeats=Math.max(...notes.map(n=>n.beat+n.duration));
 if(final){for(const [hand,pitches]of [['right',[60,72]],['left',[36,48]]])for(const pitch of pitches)notes.push({id:`h${number}-${suffix}-${hand[0]}-final-${pitch}`,pitch,beat:totalBeats,duration:4,hand});totalBeats+=4;}
 rows.push(normalizeScore({schemaVersion:2,id:`hanon-${number}${suffix?'-'+suffix:''}`,title:`哈农第 ${number} 条 · ${title}`,composer:'C. L. Hanon',collection:'哈农 · 第 III 部',level:'基本功',category:'technique',evaluationProfile:'technique',bpm,timeSignature,keySignature,notes,totalBeats,source:{label:'Schirmer 1900 · 公版原谱',url:sourceUrl,note:`独立据公版原谱印刷第 ${pages} 页转录。${description}反复段弹一遍。新转录音符数据 CC0。`},tags:['基本功','哈农',`哈农第${number}条`,title,'双手']}));
}
// Tonic registers are as printed, including the low F opening of No.56.
const keys=[['C',60,'C',98],['Am',57,'C',99],['F',53,'F',99],['Dm',62,'F',99],['Bb',58,'Bb',99],['Gm',55,'Bb',99],['Eb',63,'Eb',100],['Cm',60,'Eb',100],['Ab',56,'Ab',100],['Fm',65,'Ab',100],['Db',61,'Db',100],['Bbm',58,'Db',100],['Gb',54,'Gb',101],['Ebm',63,'Gb',101],['B',59,'B',101],['G#m',56,'B',101],['E',64,'E',101],['C#m',61,'E',101],['A',57,'A',102],['F#m',54,'A',102],['D',62,'D',102],['Bm',59,'D',102],['G',55,'G',102],['Em',64,'G',103]];
for(const[key,base,keySignature,page]of keys){
 const minor=key.endsWith('m'),scale=minor?[0,2,3,5,7,8,11]:[0,2,4,5,7,9,11];
 const diatonic=n=>base+12*Math.floor(n/7)+scale[(n%7+7)%7];
 const degrees=[...range(0,14),13,...range(12,0),1,0,-1];
 const notes=degrees.flatMap((n,i)=>{let pitch=diatonic(n);if(minor&&i===29)pitch=base+1;if(minor&&i===31)pitch=base-2;return i<16?[pitch,pitch+12]:[pitch+12,pitch];});
 add(56,key.replace('#','s'),`${key} · 分解八度音阶`,notes,notes.map(p=>p-24),{pages:page,keySignature,final:key==='Em',description:'完整原谱调性段；保留小调末尾通往下一调的变化音，末调包含全条终止八度。'});
}
// No.57: the printed, interlocking arpeggios contain 3 bars per key,
// then the four connecting octave pairs. This is not a generic triad ascent.
for(const[key,originalBase,keySignature]of keys){
 const minor=key.endsWith('m'),base=key==='F'?65:originalBase,triad=minor?[0,3,7]:[0,4,7];
 const at=n=>base+12*Math.floor(n/3)+triad[n%3];
 const broken=[0,2,1,3,2,4,3,5,4,6,5,6,4,5,3,4,2,3,1,2];
 const notes=broken.flatMap((n,i)=>i<8?[at(n),at(n)+12]:[at(n)+12,at(n)]);
 for(const pitch of [base,base+(minor?1:2),base,base-(minor?2:1)])notes.push(pitch+12,pitch);
 const index=keys.findIndex(k=>k[0]===key),pages=index<8?103:index<16?104:105;
 add(57,key.replace('#','s'),`${key} · 分解八度琶音`,notes,notes.map(p=>p-24),{pages,keySignature,bpm:40,final:key==='Em',description:'保留完整三小节交错琶音、调间连接和末调终止八度；原谱四分音符 40，目标速度 72。'});
}
return rows;
}
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url){
 const rows=transcribeHanonFinal();
 writeFileSync(new URL('../public/hanon-final.mjs',import.meta.url),'// Generated by scripts/build-hanon-final.mjs; independent source transcription CC0.\nexport const HANON_FINAL = '+JSON.stringify(rows)+';\n');
 console.log(`Built ${rows.length} final Hanon sections.`);
}
